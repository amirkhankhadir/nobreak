// Обратная правка должна указывать ровно на тот символ, который вставил детектор,
// и не выходить за границы уже исправленной строки.
(function () {
  const text = 'Ставка 20 % и рассрочка 23 360 780 ₸';
  const edits = analyze(text, ALL);
  const fixed = applyEdits(text, edits);
  const inv = inverseEdits(edits);
  let bogus = '';
  for (let i = 0; i < inv.length; i++) {
    const e = inv[i];
    if (e.at < 0 || e.at + e.len > fixed.length) { bogus = 'выход за границы'; break; }
    if (fixed.slice(e.at, e.at + e.len) !== edits[i].put) { bogus = 'указывает не на вставленный символ'; break; }
  }
  if (bogus) { bad++; console.log('✗ обратные правки: ' + bogus); } else ok++;
})();

