/* ——— правки не пересекаются ——— */
(function () {
  const edits = analyze('Цена 23 360 780 ₸ и рассрочка', ALL);
  let overlap = false, last = -1;
  for (const e of edits.slice().sort((a, b) => a.at - b.at)) {
    if (e.at < last) overlap = true;
    last = e.at + Math.max(e.len, 1);
  }
  if (overlap) { bad++; console.log('✗ правки пересекаются'); } else ok++;
})();

/* ——— откат правок: точечный, без перезаписи строки ——— */
// Кнопка «Вернуть» применяет обратные правки к уже исправленному тексту.
// Проверяем именно арифметику сдвигов: после отката должен получиться исходник.
function roundTrip(title, text, rules = ALL) {
  const edits = analyze(text, rules);
  const fixed = applyEdits(text, edits);
  const back = applyEdits(fixed, inverseEdits(edits));
  eq(title, back, text);
}
