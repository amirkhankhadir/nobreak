let ok = 0, bad = 0;

function fix(text, rules = ALL) {
  return applyEdits(text, analyze(text, rules));
}
function eq(title, got, want) {
  if (got === want) { ok++; return; }
  bad++;
  console.log('✗ ' + title);
  console.log('   получил: ' + JSON.stringify(got));
  console.log('   ожидал:  ' + JSON.stringify(want));
}
function count(title, text, want, rules = ALL) {
  const got = analyze(text, rules).length;
  if (got === want) { ok++; return; }
  bad++;
  console.log('✗ ' + title + ' — находок ' + got + ', ожидал ' + want);
}

